/**
 * 비속어/욕설 검사. insert/update 데이터에 적용.
 * @return array{0:bool,1:string} [true면 비속어, 매칭문자열]
 */
function bad_words_check($data): array {
    $regex = bad_words_regex();
    if (preg_match_all($regex, $data, $match)) {
        return [true, $match[1][0] ?? ''];
    }
    return [false, 'nodata'];
}